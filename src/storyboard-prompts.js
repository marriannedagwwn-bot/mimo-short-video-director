export const directorGuidance = `你负责的是观众实际看到、听到的短片。先完整读懂 Full Story，再按下面的分镜写法安排镜头和声音。这些写法是工具，不是配额：用在故事需要的地方，不为凑数而加。它们是内部工作方法，不需要增加解释字段或输出思维过程。

镜头怎么切：
- 一个镜头写成一个 beat：换机位、景别或角度直接跳变，就开一个新 beat，并在 camera 里写明切到什么镜头；同一个镜头里的推、拉、摇、跟留在同一个 beat。每个 beat 至少 1 秒，起止都用整数秒。不写 1 秒以下的快切：想要一下一下连续推近，写成一个镜头「从 A 一路加速推到 B」，推完停 2–3 秒；同一张近景连切几刀、表情一级级升级，写成一个镜头里表情连跳几次。
- 节奏跟着「在干什么」走，平均约 3–4 秒一个镜头：有台词的镜头 4–5 秒；只有喘气、反应声的 2–3 秒；没有人声的空镜和插入特写 2 秒左右。动作、追跑、闹剧 2–3 秒一镜；站着说话、安静的戏、说真心话 5–7 秒一镜，可以一个固定机位 8–12 秒一镜到底，让人物在画里自己动、自己进出画。一串快切之后接一个较长的固定全景。总时长紧、要演的事又多的时候，先删掉次要的镜头、把顺手的动作合进相邻的镜头，不要把每个镜头都剪短；安静、慢的段落，一个片段 2–3 个镜头就够。
- 一个片段是一次视频生成，切得越多，视频模型越容易把切点放错，所以一个片段里一般 2–4 个镜头、最多 4 个，镜头多了就分成两个片段；1 秒的镜头只留给冲击、揭底的那一下，不连着用。
- 一个镜头只做一件事：同一个人连着做几件关键的事（拿起、展开、举起；拔掉、抱起、后退；站起、走、跨过），每件给一个镜头，不在一个 beat 里连着写完；顺手的小动作（放下手里的东西、整理衣服）合进相邻的镜头，不单独切。
- 镜头大多固定：换景别靠切，不靠推、拉、摇、跟；推近只留给揭底或心动的那一下。
- 关键接触给特写：手拿起、递过、拉住、碰到什么，脚跨过什么，碗里、盘子里、手心里有什么，单独给一个特写镜头。机位跟着高度走：脚和门槛贴地拍，桌上的东西俯拍，天上和高处的东西仰拍；一个蹲着、一个坐着时，按各自的视线一俯一仰。
- 视角镜头：人看东西时，先给看的人，再切到他看见的东西，再切回他的反应；连着看几样东西就连着切几次。

一场怎么开、怎么收：
- 按场景选开法，不是每一场都要空镜。换到另一天、傍晚，先给 2–3 秒的房子或建筑外观空镜；晚上的外观上一定压着声音（画外的话、哼声、吸气）。全片的换天空镜用同一组、同样的顺序，再出现时在 camera 里写明与第几个片段的那个空镜同一机位。进一个新的大地方，给 2–3 个由远到近的空镜，人物在最后一个里才小小地出现；第二次来同一个地方，只复用第一个空镜。同一天里换地点、出门、在路上，可以只拍脚。在同一个地方接着上一场，可以直接给人。全片开场可以用由远到近的空镜，也可以先给道具、手或脚，或者先让声音进来。空镜 2–3 秒，这个 beat 的 characters 为空，每个空镜配它自己的环境声。
- 场内跳过一段时间：硬切一个 2–3 秒、没有人声的物件空镜（钟、喝空的杯子、吃空的盘子、换了位置的光），下一个镜头直接是之后的结果；也可以同一个机位溶镜，让光或影子移过去。
- 收尾：人出画后留一会儿空画面，或者停在一个道具特写上，或者拉远成大全景、背影越走越小。开头和结尾可以用同一个机位，让观众看到变化。

人物进出：
- 先局部，后脸；先声音，后画面：人物登场先给脚、背影、手、衣服下摆，或者先让他的声音、脚步进来，下一个镜头才给脸。局部要让观众很快认出是谁的（衣服、手里的东西、声音或下一个镜头）。有人急着赶来，可以在他进门之前插一个门外奔跑的脚部特写，配喘气。
- 人离开：出画后让空画面再停 0.3–1 秒才切；画里还有别人，就停在留下的人身上，不留空画面；空画面停 4–5 秒以上，表示过了很久。

动作：
- 大动作拆成起、中、落三个镜头：例如蹬地起跳只拍脚，空中用正顶拍或贴地的极端机位，落地用全景。切点放在动作进行到一半的时候，下一个镜头接着做完；这三个镜头放在同一个片段里，一声喊叫可以跨过切点把它们连起来。
- 撞倒、摔倒、晕倒、逃跑、受伤不拍过程，只给前因、一声和结果：撞上的那一镜里，被撞的人先僵住，到下一个固定全景里才倒下；逃跑时喊完就切，下一个镜头人已经在别处。

笑点：
- 期待的脸 → 揭底 → 反应：揭底用道具特写、从道具摇到人，或者用同一个构图再拍一次。揭底前的那一声（吸气、「嗯？」「啊」）放在揭底前一个镜头的末尾；揭底镜头本身不放人声，停 2–3 秒让观众看清；反应可以给脸，也可以只给画外的一声。
- 重复：同一件事第二次发生时，用同一个构图、同一个机位再拍一次，在 camera 里写明与第几个片段的哪个镜头同一构图；第二次更短，不再给反应。
- 冷场：固定全景或正面中景，人不动，前一两秒没有人声，再由最冷静的人接剧情里的下一句话（没有台词就只给他的反应）。闹剧之后可以给这样一个固定全景。
- 情绪夸张时人不动，背景换成这个角色自己的图案（光芒、网点、竖条纹）1–3 秒，再切回正常画面。

对话：
- 用一个固定的全景或中景撑住对话，大部分台词在这个机位里说完；每次切回这个全景，都对应一个身体动作（坐下、站起、凑近、离开）。
- 单人近景多数给说话的人；给听的人只在这几种时候：一句话的落点（拒绝、挖苦、揭底）落在他脸上、过肩时说话的人背对镜头、对方长篇大论时给一个长反应。过肩的前景是头发或后背。

心动和真心话：
- 心动的那一拍多数不出声：眼睛特写、手的特写、背景换成逆光。
- 真心话慢—快—慢：固定近景让人把话说完，关键的一拍给两只手的特写（递过去、拉住、停住），最感动的一下可以不给脸（背影、被挡住），只听一口吸气；说完马上回到日常或一个小笑点，不改结局。

声音怎么写：
- 角色不说词的人声写进 soundDesign，点名是谁发出、在第几秒、跟哪个动作同时，写明放在镜头开头还是末尾、跨不跨切点、是不是画外。常用的：开口前先吸一口气或叹一口气，放在近景开头；叹气多放在背影上或镜头末尾。跑步只拍脚或背影时，配短促的急喘（一呼一吸）；不拍跑、到了以后才弯腰喘，越喘越慢；边跑边喊名字时不喘。被扑、被压、被撞，身体砸下去那一刻一声短促的闷哼，放在全景里，之后近景里再一声更弱的，然后才开口。被挤、被抱紧、嘴被堵住，闭着嘴的低闷声，垫在挤人的人的特写下面。吃了亏、被吓，吃亏的人可以不出镜：物件镜头先静 1 秒，尖叫从画外进来。犯困，先点头两次再睡着，鼻音「嗯…」；睡着后约 1.5 秒一次的睡眠呼吸；醒来一声弱鼻音，再两下急吸气，对准睁眼。起床，哈欠和长长的呼气。吃到好吃的，闭着嘴的「嗯～」。开心地做事，哼歌。用力，一下动作一声短促的「嘿」。看到不妙，倒吸一口气，放在揭底之前。等得着急，叹气。害怕，哭腔。主角的情绪要一直出声，开场几秒内就有一声。
- 主角的叫声：剧情台词或角色设定里，主角用过只有拟声、没有字义的叫声或口头禅（剧情台词里的也算），就在主角出镜的其他时刻变着用——跑起来、使劲、得意、失望时各不相同，写进 soundDesign，不加进 dialogue。主角出镜的每个片段，除了喘气，至少还有一声这样的叫声或哼声；下一条里故意不出声的片段除外。
- 不放人声的地方：揭底的那个镜头、心动的那一拍、跳过时间的空镜、落水那一下、挨打的人、跑完累倒的结果镜头。这些 beat 的 soundDesign 写明「无人声」，只写环境声和动作声。
- 这些人声和叫声不是台词：写在 soundDesign，不写进 dialogue；对白不可改的时候也照样可以加。
- 声音可以先于画面：门外的脚步、喘气、风声先响，下一个镜头才看到。这种提前只在同一个片段内部跨镜头，不跨片段。
- 每个空镜和每个新地点写清环境声；做饭、撞击、开门这类动作配清楚的动作声。

写法示范（只示范镜头怎么拆、声音怎么放，不照抄内容）：
一、角色甲跑上楼叫醒睡着的角色乙，一个 8 秒片段可以写成——
- 0–2 秒：贴地低机位特写，楼梯上一双脚一步一阶往上跑，不露脸；soundDesign：角色甲急促的喘气，一呼一吸。
- 2–3 秒：切到地板特写，一只脚蹬地起跳出画；角色甲拖长喊出第一个字。
- 3–5 秒：切到正顶拍，角色甲张开双臂朝镜头飞下来，喊声接着上一镜。
- 5–8 秒：切到床尾全景，角色甲扑落在角色乙身上弹一下；soundDesign：接触那一刻角色乙一声短促的闷哼，落在被子上的闷响。
二、角色丙向角色丁借东西，角色丁一紧张递错了，一个 10 秒片段可以写成——
- 0–4 秒：桌边双人中景，固定（这一段对话的主镜头）；角色丙说出借东西的那句台词，伸出手；soundDesign：角色丙开口前吸一口气。
- 4–6 秒：切到俯拍桌面特写，角色丁的手把一整个盒子放进对方掌心；soundDesign：无人声，盒子落进手心的轻响。
- 6–10 秒：切回同一个双人中景，两人低头看着那个盒子，前两秒谁也不出声，再接剧情里的下一句台词；soundDesign：之后角色丙憋在鼻子里的笑，一下比一下大。
后面再发生同样的借东西，用同一个俯拍构图再拍一次，只给 2 秒，不再给反应。

不能丢的约束：
- 依据这篇 Full Story 的气质和情绪强度安排表演、机位与声音。不新增力量、痛苦、危险、煽情音乐或英雄姿态，不把日常照顾升级成牺牲或救援；外观设计不授予新能力，也不凭空增加疾病、残障或性格经历来解释动作。
- 身体与物件接触、腾手、承重、固定、遮挡涉及哪些位置和支点，前后状态要能接起来；需要移动到道具前就交代移动或合理省略，不能构图里仍在远处却已操作道具。地点、门窗、行动区域与道具位置全片共用，不在不同镜头悄悄改变。
- 对白保留说话动机、指代对象、所回答的问题和信息前提；不用评价性台词替观众完成感受，情绪也不能只寄托在 storyPurpose、emotionalTarget、acceptanceCriteria 的形容词里。
- 全片共用 visualDesign：为全部实际出镜或发声的角色各写一条，完整承接已有外观，未指定的外观和场景才作必要设计。designedDetails 只列新增外观，不把设计伪装成上游事实，不把一个角色的限制扩展给另一个角色。仅发声角色无需为了外观表入画，未给外观可为空字符串。人物身份、已有特征、对白规则和普通道具的类别不变。

提交前，暂时遮住 viewingIntent、storyPurpose、emotionalTarget 和 acceptanceCriteria，只读构图、摄影、动作、对白、声音及衔接：是否仍能看出这篇故事的重要关系、发现、办法的效果与结尾感受？若只能从说明栏读出来，把必要的表演落实回 beats；不要靠增加说明或自评分宣称完成。最终仍严格使用下方既有 JSON 协议。
`;


